export const BANK_CATALOG_RECORDS: readonly NewBankCatalogEntry[] = providerBanks.map(
  ([code, name]) => ({ code, name, country: 'Nigeria', currency: 'NGN' }),
);

/** Inserts the provider bank directory without deduplicating provider aliases. */
export const seedBankCatalog = async (tx: SeedTransaction): Promise<number> => {
  const inserted = await tx.insert(bankCatalog).values([...BANK_CATALOG_RECORDS])
    .returning({ id: bankCatalog.id });
  if (inserted.length !== BANK_CATALOG_RECORDS.length) {
    throw new Error('Bank catalog seed did not create every provider record');
  }
  return inserted.length;
};
